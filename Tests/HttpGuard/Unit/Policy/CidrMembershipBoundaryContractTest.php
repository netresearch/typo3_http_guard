            yield [$text];
        }
    }

    public function testMappedCandidatesUseV4MembershipWithoutV6FamilyLeak(): void
    {
        $classifier = new AddressClassifier();
        self::assertTrue($classifier->contains('10.23.4.0/24', '::ffff:10.23.4.12'));
        self::assertFalse($classifier->contains('10.23.4.0/24', '::ffff:10.23.5.12'));
        self::assertFalse($classifier->contains('10.23.4.0/24', 'not-an-ip'));
        self::assertFalse($classifier->contains('2001:db8::/32', '10.23.4.12'));
        self::assertSame('::a17:40c', Cidr::address('::10.23.4.12'));
        self::assertSame('10.23.4.12', Cidr::address('::ffff:10.23.4.12'));
        self::assertSame('2001:db8::/32', Cidr::parse('2001:0DB8::/32', false)->cidr);
    }
