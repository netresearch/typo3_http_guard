    #[DataProvider('networkBoundaries')]
    public function testEveryPrefixContainsFirstAndLastButNeverAdjacentAddress(
        string $text,
        string $first,
        string $last,
        ?string $before,
        ?string $after,
    ): void {
        $network = Cidr::parse($text);
        self::assertSame($text, $network->cidr);
        self::assertTrue($network->contains($first));
        self::assertTrue($network->contains($last));
        self::assertTrue($network->containsPacked(inet_pton($first)));
        self::assertTrue($network->containsPacked(inet_pton($last)));
        if ($before !== null) {
            self::assertFalse($network->contains($before));
        }
        if ($after !== null) {
            self::assertFalse($network->contains($after));
        }
        self::assertFalse($network->containsPacked(inet_pton($network->family === 4 ? '::1' : '127.0.0.1')));
    }

